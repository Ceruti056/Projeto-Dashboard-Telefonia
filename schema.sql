-- Script SQL para criar a tabela de chamadas de telefonia no Supabase
-- Você pode colar este script diretamente no Supabase: SQL Editor -> New Query -> Run

CREATE TABLE IF NOT EXISTS public.chamadas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_hora TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    operador TEXT NOT NULL,
    departamento TEXT NOT NULL,
    tipo TEXT NOT NULL DEFAULT 'Entrante',
    canal TEXT NOT NULL DEFAULT 'Voz (0800)',
    status TEXT NOT NULL DEFAULT 'Resolvido',
    duracao_segundos INTEGER NOT NULL DEFAULT 180,
    tempo_espera_segundos INTEGER NOT NULL DEFAULT 30,
    avaliacao_satisfacao INTEGER CHECK (avaliacao_satisfacao >= 1 AND avaliacao_satisfacao <= 5),
    custo_ligacao_reais NUMERIC(10,2) DEFAULT 0.00,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

